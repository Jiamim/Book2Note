def p(text, cls=""):
    return f'<p class="{cls}">{text}</p>'


def col(*items):
    return '<div class="columns ' + ("three" if len(items) == 3 else "") + '">' + "".join("<div>" + x + "</div>" for x in items) + "</div>"


def h(title, text):
    return "<h3>" + title + "</h3>" + text


def table(heads, rows, tight=False):
    return '<table class="editorial-table ' + ("tight" if tight else "") + '"><thead><tr>' + "".join("<th>" + x + "</th>" for x in heads) + "</tr></thead><tbody>" + "".join("<tr>" + "".join("<td>" + x + "</td>" for x in row) + "</tr>" for row in rows) + "</tbody></table>"


def steps(items):
    return '<div class="steps">' + "".join(f'<div class="step"><div class="step-no">{i:02d}</div><h3>{title}</h3>{p(copy)}</div>' for i, (title, copy) in enumerate(items, 1)) + "</div>"


